#!/usr/bin/env python3
"""Embeds scrollapp.js into ScrollApp/Feed/PageScript.swift.

The page script is shared with the Android app (ScrollApp/app/src/main/assets/scrollapp.js).
After changing it there, copy it here and run: python3 PageScript/embed.py
It is embedded as Swift source rather than bundled as a resource because Xcode puts .js files
in the Compile Sources phase instead of copying them into the app.
"""
from pathlib import Path

here = Path(__file__).resolve().parent
script = (here / "scrollapp.js").read_text(encoding="utf-8")
if '"""#' in script:
    raise SystemExit('scrollapp.js contains """#, which would end the Swift raw string')

out = here.parent / "ScrollApp" / "Feed" / "PageScript.swift"
out.write_text(
    "// Generated by PageScript/embed.py from PageScript/scrollapp.js. Do not edit by hand.\n\n"
    "enum PageScript {\n"
    '    static let source = #"""\n'
    + script.rstrip("\n")
    + '\n"""#\n'
    "}\n",
    encoding="utf-8",
)
print(f"wrote {out.relative_to(here.parent)} ({len(script)} chars)")
